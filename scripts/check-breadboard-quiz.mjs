import assert from 'node:assert/strict';
import {validateCircuit,connectionError,createLayout} from '../public/scripts/breadboard-quiz/model.js';
const wires=tuples=>tuples.map(([from,to],i)=>({id:`test-${i}`,from,to,color:'#0b8b83'}));
const one=[['R1.1','P2'],['R1.2','A3'],['L1.A','C3'],['L1.K','N2']];
assert(validateCircuit(wires(one),1),'LED and series resistor on a shared strip');
assert(validateCircuit(wires([['L1.A','P9'],['L1.K','J12'],['R1.2','I12'],['R1.1','N10']]),1),'resistor after LED, lower bank, arbitrary holes');
assert(!validateCircuit([],1),'empty circuit is not solved');
assert(!validateCircuit(wires(one.slice(0,3)),1),'open LED leg');
assert(!validateCircuit(wires(one.map(([a,b])=>[a==='L1.A'?'L1.K':a==='L1.K'?'L1.A':a,b])),1),'reversed LED');
assert(!validateCircuit(wires(one.map(([a,b])=>[a,b==='C3'?'F3':b])),1),'same column across center trench is isolated');
assert(!validateCircuit(wires([...one,['P3','N3']]),1),'supply short via jumper');
assert(!validateCircuit(wires([['R1.1','A3'],['R1.2','B3'],['L1.A','C3'],['L1.K','N2'],['P2','D3']]),1),'resistor bypassed by one copper strip');
const three=[...one,['R2.1','P3'],['R2.2','A6'],['L2.A','E6'],['L2.K','N3'],['R3.1','P4'],['R3.2','F10'],['L3.A','J10'],['L3.K','N4']];
assert(validateCircuit(wires(three),3),'three independent branches');
const after=Array.from({length:3},(_,i)=>[[`L${i+1}.A`,`P${i+2}`],[`L${i+1}.K`,`A${i+4}`],[`R${i+1}.1`,`B${i+4}`],[`R${i+1}.2`,`N${i+2}`]]).flat();
assert(validateCircuit(wires(after),3),'all three resistors can be on ground side');
const shared=Array.from({length:3},(_,i)=>[[`R${i+1}.1`,`P${i+2}`],[`R${i+1}.2`,`BP${i+2}`],[`L${i+1}.A`,`BP${i+5}`],[`L${i+1}.K`,`N${i+2}`]]).flat();
assert(!validateCircuit(wires(shared),3),'parallel resistors feeding a common LED bank are not dedicated per LED');
const bridged=[['P2','BP2'],['N2','BN2'],['R1.1','BP3'],['R1.2','F8'],['L1.A','H8'],['L1.K','BN3']];
assert(validateCircuit(wires(bridged),1),'top and bottom rails correctly bridged');
assert(!validateCircuit(wires(bridged.slice(2)),1),'bottom rails without source jumpers are unpowered');
assert(connectionError(wires(one),'L1.A','A7',1),'occupied lead cannot gain a second wire');
assert.equal(connectionError(wires(one),'L1.A','A7',1,'test-2'),null,'rewiring replaces the existing endpoint');
assert(connectionError([], 'P1','A2',1),'fixed supply holes are occupied');
assert(connectionError([], 'L1.A','R1.2',1),'component legs must be inserted in breadboard holes');
assert(!validateCircuit([{id:'bad',from:'missing',to:'P2'}],1),'unknown terminals cannot pass');
assert.equal(new Set(createLayout(3).points.map(p=>p.id)).size,264);
console.log('Breadboard quiz checks passed: arbitrary placements, both resistor orders, three independent branches, polarity, open circuits, shorts, bypasses, shared resistors, rail bridges and occupancy.');

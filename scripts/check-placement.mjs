import assert from 'node:assert/strict';
import {holePair,placementError,insertedWires,sceneLayout,validPlacedState,nearestPlacement} from '../public/scripts/breadboard-quiz/placement.js';
import {validateCircuit} from '../public/scripts/breadboard-quiz/model.js';
import {analyzeCircuit} from '../public/scripts/breadboard-quiz/analysis.js';
const jumpers=p=>p.map(([from,to],i)=>({id:`j${i}`,from,to}));
assert.deepEqual(holePair('L1','A3',0,1).map(p=>p.id),['A3','A4']);
assert.deepEqual(holePair('L1','A3',90,1).map(p=>p.id),['A3','B3']);
assert.deepEqual(holePair('R1','A3',0,1).map(p=>p.id),['A3','A6']);
assert.deepEqual(holePair('R1','P3',90,1).map(p=>p.id),['P3','B3']);
assert.equal(holePair('R1','J18',0,1),null);
assert.equal(holePair('L1','A1',180,1),null);
const poses={R1:{anchor:'A3',rotation:0},L1:{anchor:'D7',rotation:0}};
const pins=[...insertedWires('R1','A3',0,1),...insertedWires('L1','D7',0,1)];
const wires=[...pins,...jumpers([['P2','B3'],['B6','B7'],['B8','N2']])];
assert(validPlacedState(poses,wires,1));assert(validateCircuit(wires,1));
assert(analyzeCircuit(wires,1).totalCurrent>.0037);
assert(placementError('L1','A6',0,1,pins),'one physical pin per hole');
assert(placementError('R1','P1',0,1,[]),'supply feed occupied');
assert.equal(placementError('R1','A3',90,1,pins),null,'own pins can be rotated');
const scene=sceneLayout(1,poses);assert.equal(scene.points.find(p=>p.id==='L1.A').x,444);assert.equal(scene.points.find(p=>p.id==='L1.A').y,495);assert.equal(scene.points.filter(p=>p.id==='D7').length,1,'leg ids are not overwritten by hole ids');
assert(nearestPlacement('R1',{x:444,y:495},0,1,pins)?.error,'snap respects occupied pin holes');
assert.equal(nearestPlacement('L1',{x:20,y:100},0,1,[]),null);
const vertical={R1:{anchor:'P3',rotation:90},L1:{anchor:'D3',rotation:0}};
const w2=[...insertedWires('R1','P3',90,1),...insertedWires('L1','D3',0,1),...jumpers([['B4','N2']])];
assert(validPlacedState(vertical,w2,1));assert(validateCircuit(w2,1));
const shortLED={L1:{anchor:'A3',rotation:90},R1:{anchor:'F4',rotation:0}};
const w3=[...insertedWires('L1','A3',90,1),...insertedWires('R1','F4',0,1)];assert(validPlacedState(shortLED,w3,1));assert(!validateCircuit(w3,1),'physical fit is distinct from electrical correctness');
console.log('Placement passed: rotation, two-leg footprints, bounds, occupancy, dynamic coordinates, physical/electrical distinction and live current.');
